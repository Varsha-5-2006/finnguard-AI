import { Response } from 'express';
import { db } from '../db/database.js';
import { AuthenticatedRequest, logAuditEvent } from '../middleware/auth.js';

export class ComplianceController {
  public static async generateReport(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const { reportType = 'aml_quarterly', startDate, endDate, title } = req.body;
      const transactions = db.getTransactions();
      const alerts = db.getAlerts();
      const cases = db.getCases();
      const auditEvents = db.getAuditEvents();

      const startTime = startDate ? new Date(startDate).getTime() : Date.now() - 30 * 86400000;
      const endTime = endDate ? new Date(endDate).getTime() : Date.now();

      const filteredTransactions = transactions.filter(t => {
        const time = new Date(t.timestamp).getTime();
        return time >= startTime && time <= endTime;
      });

      const totalTx = filteredTransactions.length;
      const totalVolume = filteredTransactions.reduce((acc, t) => acc + t.amount, 0);
      const flaggedTx = filteredTransactions.filter(t => t.riskScore >= 50);
      const blockedTx = filteredTransactions.filter(t => t.status === 'blocked');
      const confirmedFraudTx = filteredTransactions.filter(t => t.reviewedOutcome === 'confirmed_fraud');
      const confirmedFraudAmount = confirmedFraudTx.reduce((acc, t) => acc + t.amount, 0);

      const highRiskAlerts = alerts.filter(a => {
        const time = new Date(a.createdAt).getTime();
        return time >= startTime && time <= endTime && (a.severity === 'high' || a.severity === 'critical');
      });

      const closedCases = cases.filter(c => {
        const time = new Date(c.createdAt).getTime();
        return time >= startTime && time <= endTime && c.status === 'closed';
      });

      const reportId = `REP-${Date.now().toString(36).toUpperCase()}-${Math.floor(100 + Math.random() * 900)}`;
      const generatedAt = new Date().toISOString();

      const reportData = {
        reportId,
        title: title || 'Comprehensive AML & Anti-Fraud Compliance Audit Report',
        reportType,
        period: {
          startDate: new Date(startTime).toISOString().split('T')[0],
          endDate: new Date(endTime).toISOString().split('T')[0],
        },
        generatedAt,
        generatedBy: {
          id: req.user?.id || 'sys',
          name: req.user?.name || 'Compliance Officer',
          role: req.user?.role || 'compliance',
        },
        summary: {
          totalTransactionsMonitored: totalTx,
          totalMonitoredVolume: totalVolume,
          flaggedTransactionsCount: flaggedTx.length,
          blockedTransactionsCount: blockedTx.length,
          confirmedFraudCasesCount: closedCases.filter(c => c.disposition === 'confirmed_fraud').length,
          confirmedFraudLossPrevented: confirmedFraudAmount,
          highRiskAlertsGenerated: highRiskAlerts.length,
          auditEventsLoggedCount: auditEvents.length,
        },
        highRiskHighlights: flaggedTx.slice(0, 10).map(t => ({
          transactionId: t.transactionId,
          customerName: t.customerName,
          amount: t.amount,
          currency: t.currency,
          riskScore: t.riskScore,
          riskLevel: t.riskLevel,
          triggeredRules: t.triggeredRules.map(r => r.name),
          recommendedAction: t.recommendedAction,
          reviewedOutcome: t.reviewedOutcome,
        })),
        regulatoryNote: 'Notice: This report is generated by FinGuard AI for internal risk management, institutional oversight, and AML/BSA compliance review. It does not replace independent legal verification or statutory filings.',
      };

      logAuditEvent(
        req,
        'GENERATE_COMPLIANCE_REPORT',
        'compliance_report',
        reportId,
        `Generated compliance report "${reportData.title}" (${reportType}).`
      );

      res.json({ report: reportData });
    } catch (err: any) {
      res.status(500).json({ error: 'Failed to generate compliance report: ' + err.message });
    }
  }

  public static async listAuditEvents(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const {
        actorRole,
        targetEntity,
        search = '',
        page = '1',
        limit = '25',
      } = req.query as Record<string, string>;

      let items = [...db.getAuditEvents()];

      if (actorRole && actorRole !== 'all') {
        items = items.filter(e => e.actorRole === actorRole);
      }
      if (targetEntity && targetEntity !== 'all') {
        items = items.filter(e => e.targetEntity === targetEntity);
      }
      if (search && search.trim()) {
        const q = search.trim().toLowerCase();
        items = items.filter(e =>
          (e.actorName || '').toLowerCase().includes(q) ||
          (e.action || '').toLowerCase().includes(q) ||
          (e.details || '').toLowerCase().includes(q) ||
          (e.entityId || '').toLowerCase().includes(q)
        );
      }

      // Sort descending by timestamp so newest audit events appear first
      items.sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime());

      const total = items.length;
      const pageNum = Math.max(1, parseInt(page, 10) || 1);
      const limitNum = Math.max(1, Math.min(100, parseInt(limit, 10) || 25));
      const paginated = items.slice((pageNum - 1) * limitNum, pageNum * limitNum);

      res.json({
        auditEvents: paginated,
        pagination: {
          page: pageNum,
          limit: limitNum,
          total,
          totalPages: Math.ceil(total / limitNum),
        },
      });
    } catch (err: any) {
      res.status(500).json({ error: 'Failed to retrieve audit log: ' + err.message });
    }
  }
}
